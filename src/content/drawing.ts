export function drawingTheme(host: NarratorId, variant: number): DrawingTheme {
  const t = themes[host],
    choice = index(variant, t.titles.length);
  return {
    title: t.titles[choice],
    interest: t.interest,
    subject: t.subject,
    first: t.first.replace("PLACE", t.places[choice]),
    change: t.change,
    meeting: t.meeting,
  };
}
