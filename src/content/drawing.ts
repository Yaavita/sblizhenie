function shuffle<T>(items: readonly T[], seed: number): T[] {
  const result = [...items];
  let s = (Math.trunc(seed) | 0) ^ 0x6d2b79f5;
  for (let i = result.length - 1; i > 0; i--) {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    const j = (s >>> 0) % (i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
export function drawingScenes(
  host: NarratorId,
  variant: number,
): DrawingScene[] {
  const visitors = shuffle<NarratorId>(
    ["noise", "momo", "archivist", "chance", "noir"].filter(
      (n) => n !== host,
    ) as NarratorId[],
    variant ^ 0x7a31,
  );
  const decks = visitors.map((n, i) =>
    shuffle(
      drawingScenePool.filter((s) => s.narrator === n),
      variant * 31 + i * 7919,
    ),
  );
  return Array.from(
    { length: 6 },
    (_, i) => decks[i % decks.length][Math.floor(i / decks.length)],
  );
}

