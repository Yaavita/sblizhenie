export function drawingStages(
  host: NarratorId,
  variant: number,
  intimacy: number,
): Stage[] {
  const theme = drawingTheme(host, variant),
    detail = levelDetails[index(intimacy, 3)];
  const stages: Stage[] = [
    {
      id: "d-base",
      title: theme.title,
      body: `${theme.first} ${detail}`,
      seconds: 600,
      kind: "drawing",
      target: "both",
      prompt:
        "Продолжайте карту сверху, небольшими значками. Займите только треть листа; остальное нужно для новых деталей.",
    },
    {
      id: "d-remix",
      title: "У готового рисунка новая жизнь",
      body: `${theme.change} ${detail}`,
      seconds: 600,
      kind: "drawing",
      target: "both",
      prompt:
        "Продолжайте на том же листе. Меняется смысл деталей, а не сам лист.",
    },
    {
      id: "d-guest",
      title: "Впустить другого",
      body: `${theme.meeting} ${detail}`,
      seconds: 600,
      kind: "drawing",
      target: "both",
      prompt:
        "Добавляйте небольшие детали. Каждая прежняя линия остаётся частью истории.",
    },
    {
      id: "d-gallery",
      title: "Два рисунка и их приключения",
      body: `Покажите рисунки по очереди. Найдите деталь, которую пришлось переделать после спора ведущих. ${detail}`,
      seconds: 420,
      kind: "drawing",
      target: "both",
      prompt:
        host === "momo"
          ? "Человек, чей мир нарисован, расскажет, что совпало с ним, а что оказалось неожиданной догадкой."
          : "Какое случайное вмешательство сделало рисунок интереснее первоначального плана?",
    },
  ];
  return stages.map((stage, chapter) =>
    chapter === 3
      ? stage
      : {
          ...stage,
          seconds: 540 + 360 * (chapter === index(variant, 3) ? 2 : 1),
        },
  );
}

