/** 27 minutes of core drawing, 24 minutes of disputes inside the turns, seven-minute guessing finale. */
export function drawingPlan(config: DrawingConfig): DrawingCue[] {
  const { host, variant, intimacy } = config;
  const stages = drawingStages(host, variant, intimacy),
    scenes = drawingScenes(host, variant);
  const plan: DrawingCue[] = [];
  let sceneIndex = 0,
    soloChapter = 0;
  for (let chapter = 0; chapter < 3; chapter++) {
    const stage = stages[chapter],
      double = chapter === index(variant, 3);
    const soloArtist = (soloChapter % 2) as 0 | 1;
    if (!double) soloChapter++;
    const order: (0 | 1)[] = chapter % 2 === 0 ? [0, 1] : [1, 0];
    for (const artist of order) {
      const hasScene = double || artist === soloArtist;
      const opening = hasScene
        ? [75, 150, 210][index(variant + chapter + artist, 3)]
        : 270;
      const story = stories[host][chapter];
      plan.push({
        id: `${stage.id}-${artist}`,
        chapter,
        kind: "main",
        narrator: host,
        title: stage.title,
        text: `${stage.body}\n\n${stage.prompt}`,
        seconds: opening,
        artist,
        story,
      });
      if (hasScene) {
        const scene = scenes[sceneIndex++],
          id = `d-${chapter}-${artist}-${scene.id}`;
        plan.push({
          id,
          chapter,
          kind: "addition",
          narrator: scene.narrator,
          title: scene.title,
          text: scene.addition,
          seconds: 180,
          artist,
          story,
        });
        plan.push({
          id: `${id}-revision`,
          chapter,
          kind: "revision",
          narrator: scene.opponent,
          title: "Правило меняется. Штрихи остаются.",
          text: scene.revision,
          seconds: 180,
          supersedes: id,
          artist,
          story,
          retort: { narrator: scene.narrator, text: scene.retort, after: 90 },
        });
        plan.push({
          id: `${id}-quiet`,
          chapter,
          kind: "quiet",
          narrator: host,
          title: "Спокойно дорисовываем",
          text: "Продолжайте по заданиям для этого рисунка. Рассказчик может добавить подробности или дать спокойно дорисовать.",
          seconds: 270 - opening,
          artist,
          story,
        });
      }
    }
  }
  plan.push({
    id: "d-gallery-one",
    chapter: 3,
    kind: "gallery",
    narrator: host,
    title: "Игрок 1 угадывает свой мир",
    text: "Игрок 2, молча покажи свой рисунок о человеке напротив. Игрок 1, выбери три детали и предположи: что это, во время какого рассказа появилось и о чём думал автор. Сначала все три догадки, затем игрок 2 объясняет. Угадать буквально не обязательно — интереснее сравнить версии.",
    seconds: 180,
    player: 0,
  });
  plan.push({
    id: "d-gallery-two",
    chapter: 3,
    kind: "gallery",
    narrator: host,
    title: "Игрок 2 угадывает свой мир",
    text: "Игрок 1, молча покажи рисунок. Игрок 2, выбери три детали: что здесь изображено, какой рассказ их подсказал и что автор хотел показать? Сначала догадки, потом игрок 1 объясняет. Найдите хотя бы одно неожиданное совпадение или забавное расхождение.",
    seconds: 180,
    player: 1,
  });
  plan.push({
    id: "d-gallery-together",
    chapter: 3,
    kind: "gallery",
    narrator: host,
    title: stages[3].title,
    text: "Положите рисунки рядом. Каждый выберите любимое превращение после спора ведущих и придумайте название своему рисунку. Что в чужом рисунке оказалось совсем не таким, как вы ожидали?",
    seconds: 60,
  });
  return plan;
}
