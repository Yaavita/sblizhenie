function shuffle<T>(values: readonly T[], seed: number): T[] {
  const deck = [...values];
  let random = (Math.trunc(seed) | 0) ^ 0x6d2b79f5;
  for (let i = deck.length - 1; i > 0; i--) {
    random ^= random << 13;
    random ^= random >>> 17;
    random ^= random << 5;
    const j = (random >>> 0) % (i + 1);
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}
export const syncRounds = (variant: number) =>
  shuffle(syncPrompts, variant ^ 0x713a).slice(0, 8);
export function syncOptions(variant: number, round: number, player: 0 | 1) {
  const prompt = syncRounds(variant)[round];
  const order = shuffle([0, 1, 2], variant ^ Math.imul(round + 1, 7919));
  // Different orders prevent matching by button position instead of association.
  if (player === 1) order.push(order.shift()!);
  return order.map((choice) => ({ choice, label: prompt.options[choice] }));
}
export function pitchRounds(variant: number) {
  const items = shuffle(products, variant ^ 0x10a);
  const people = shuffle(customers, variant ^ 0x20b);
  const questions = shuffle(objections, variant ^ 0x30c);
  return items.slice(0, 6).map((product, index) => ({
    product,
    customer: people[index],
    objection: questions[index],
  }));
}
