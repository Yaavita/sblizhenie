/** Adds concrete host constraints while preserving stage identity, timing and all mystery facts. */
export function applyHostStages(
  stages: Stage[],
  game: GameId,
  narrator: NarratorId,
  variant: number,
  intimacy: number,
): Stage[] {
  const tasks =
    game === "universes"
      ? drawingTasks(narrator, variant, intimacy)
      : game === "cult"
        ? cultTasks[narrator]
        : game === "secrets"
          ? investigationTasks[narrator]
          : {};

  return stages.map((stage) => {
    if (game === "auction") return stage;

    const task = tasks[stage.id];
    if (!task) return stage;
    // Mystery testimony and secret payloads remain byte-for-byte intact; only investigation method changes.
    if (game === "secrets")
      return {
        ...stage,
        prompt: stage.prompt ? `${stage.prompt}\n\n${task}` : task,
      };
    return { ...stage, body: `${stage.body}\n\n${task}` };
  });
}
