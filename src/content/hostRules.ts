export function getHostRules(
  narrator: NarratorId,
  game: GameId,
  intimacy = 0,
): HostRule[] {
  if (game === "pitch" || game === "sync")
    return [
      {
        id: `${game}-turns`,
        title: "По очереди",
        text: "На каждом экране выделен игрок, который сейчас действует. Задания выполняются по одному.",
      },
      {
        id: `${game}-score`,
        title: "Итоги",
        text:
          game === "sync"
            ? "За каждый одинаковый ответ — один общий балл. Всего восемь раундов."
            : "У каждого три продажи. Первые две дают по баллу, последняя — два. Решает покупатель.",
      },
    ];
  if (game === "museum")
    return [
      {
        id: "museum-stories",
        title: "История за впечатлением",
        text: "Каждый готовит три подписи о себе. Другой выбирает, о какой услышать историю. Рассказывайте по очереди.",
      },
      {
        id: "museum-captions",
        title: "Подпись принадлежит автору",
        text: "Слушающий предлагает более точную подпись. Автор истории подтверждает её или просит уточнить. Все шесть подписей останутся в вашей выставке.",
      },
    ];
  return rules[game][narrator].map(([id, title, text]) => ({
    id: `${game}-${narrator}-${id}`,
    title,
    text:
      narrator === "noir" &&
      game === "universes" &&
      intimacy >= 2 &&
      id === "shadow"
        ? "Нарисуйте тайную комнату и желание, которое добавляет вашему будущему притяжения. Его можно оставить символом, рассказать намёком или описать прямо."
        : text,
  }));
}

