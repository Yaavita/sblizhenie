/** Seeded Fisher–Yates, no Math.random calls during rendering or session restoration. */
function shuffled<T>(items: readonly T[], variant: number): T[] {
  const result = [...items];
  let state = (Math.trunc(variant) | 0) ^ 0x6d2b79f5;
  for (let i = result.length - 1; i > 0; i--) {
    state ^= state << 13;
    state ^= state >>> 17;
    state ^= state << 5;
    const j = (state >>> 0) % (i + 1);
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

export function selectStoryLots(
  variant: number,
  intimacy: number,
  count = 10,
): StoryLot[] {
  const hosts = shuffled<AuctionHost>(
    ["noise", "momo", "archivist", "noir"],
    variant ^ 0x43fa,
  );
  const decks = hosts.map((narrator, index) =>
    shuffled(
      storyLots.filter((lot) => lot.narrator === narrator),
      variant * 31 + index * 7919,
    ),
  );
  const selected: StoryLot[] = [];
  const limit = Math.min(60, Math.max(0, Math.trunc(count)));
  for (let round = 0; round < 15 && selected.length < limit; round++) {
    for (const deck of decks) {
      if (selected.length === limit) break;
      selected.push(deck[round]);
    }
  }
  const level = intimacyLevel(intimacy);
  return shuffled(selected, variant ^ 0x51be).map((lot) => ({
    ...lot,
    ...(level === 0 ? gentleLotLabels[lot.id] : {}),
    question: lotQuestion(lot.id, level, lot.question),
  }));
}

export function selectBonusQuestion(
  variant: number,
  intimacy: number,
  usedIds: readonly string[] = [],
): BonusQuestion | null {
  const level = intimacyLevel(intimacy);
  const used = new Set(usedIds);
  const pool = bonusQuestions.filter(
    (question) =>
      question.narrator === "chance" &&
      question.minIntimacy <= level &&
      !used.has(question.id),
  );
  const selected = shuffled(pool, variant)[0];
  return selected
    ? { ...selected, question: selected.versions?.[level] ?? selected.question }
    : null;
}
