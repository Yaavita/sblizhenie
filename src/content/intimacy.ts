export function intimacyLevel(value: number): Intimacy {
  return value === 1 || value === 2 ? value : 0;
}
export function sharedIntimacy(first: number, second: number): Intimacy {
  return Math.min(intimacyLevel(first), intimacyLevel(second)) as Intimacy;
}
